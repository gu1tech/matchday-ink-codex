"""Generate deterministic four-ink icons for Python preview and the physical ESP framebuffer."""
import json
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]


def tile():
    im = Image.new('L', (13, 13), 3)
    ImageDraw.Draw(im).rounded_rectangle((0, 0, 12, 12), radius=2, fill=1)
    return im


icons = {}
for state in ['on', 'off', 'unknown']:
    im = tile()
    d = ImageDraw.Draw(im)
    for points in [[(1, 4), (3, 2), (5, 1), (7, 1), (9, 2), (11, 4)],
                   [(3, 6), (5, 4), (7, 4), (9, 6)], [(5, 8), (6, 7), (7, 8)]]:
        d.line(points, fill=0, width=1)
    if state == 'unknown':
        d.rectangle((5, 10, 7, 12), outline=0)
    else:
        d.rectangle((6, 10, 6, 11), fill=0)
    if state == 'off':
        d.line((1, 11, 11, 1), fill=3, width=2)
    icons['wifi_' + state] = list(im.getdata())
for fresh in [True, False]:
    im = tile()
    d = ImageDraw.Draw(im)
    ink = 0 if fresh else 3
    d.ellipse((1, 1, 11, 11), outline=ink)
    if fresh:
        d.line([(3, 6), (5, 8), (9, 4)], fill=ink, width=1)
    else:
        d.line([(6, 3), (6, 6), (9, 7)], fill=ink, width=1)
    icons['data_fresh' if fresh else 'data_stale'] = list(im.getdata())
asset = ROOT / 'src/matchday/assets/status-icons.json'
asset.write_text(json.dumps(icons, separators=(',', ':')))
lines = ['#pragma once', '#include <stdint.h>', '// Generated by scripts/generate_status_icons.py.']
for name, pixels in icons.items():
    lines.append('static constexpr uint8_t MATCHDAY_INK_' + name.upper() + '[169] = {'
                 + ','.join(map(str, pixels)) + '};')
lines += ['''inline void matchdayInkFramePixel(uint8_t *frame, int x, int y, uint8_t color) {
  const int panelX = 127 - y;
  const int index = x * 32 + panelX / 4;
  const int shift = 6 - 2 * (panelX % 4);
  frame[index] = (frame[index] & ~(3u << shift)) | ((color & 3u) << shift);
}
inline void matchdayInkStatusIcons(uint8_t *frame, bool connected, bool fresh) {
  const uint8_t *wifi = connected ? MATCHDAY_INK_WIFI_ON : MATCHDAY_INK_WIFI_OFF;
  const uint8_t *data = fresh ? MATCHDAY_INK_DATA_FRESH : MATCHDAY_INK_DATA_STALE;
  for (int y = 0; y < 13; ++y) for (int x = 0; x < 13; ++x) {
    matchdayInkFramePixel(frame, 263 + x, 6 + y, wifi[y * 13 + x]);
    matchdayInkFramePixel(frame, 280 + x, 6 + y, data[y * 13 + x]);
  }
}''']
(ROOT / 'firmware/MatchdayInk/frame_status.h').write_text('\n'.join(lines) + '\n')
print('Status icon asset and firmware header generated.')
